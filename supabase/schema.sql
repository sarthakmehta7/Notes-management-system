-- SLIET Notes Portal production schema
-- Run this in Supabase SQL Editor.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  roll_no text,
  branch text,
  semester text,
  verified boolean not null default false,
  role text not null default 'student',
  created_at timestamptz not null default now()
);

create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  name text not null,
  code text,
  branch text,
  semester text,
  created_at timestamptz not null default now(),
  unique(name, branch, semester)
);

create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  subject_id bigint references public.subjects(id) on delete set null,
  title text not null,
  subject text not null,
  semester text,
  description text,
  original_name text not null,
  storage_path text not null,
  mime_type text not null,
  file_size bigint not null,
  downloads integer not null default 0,
  category text not null default 'study-material',
  tags text not null default '',
  visibility text not null default 'class',
  archived boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.users add column if not exists role text not null default 'student';
alter table public.notes add column if not exists category text not null default 'study-material';
alter table public.notes add column if not exists tags text not null default '';
alter table public.notes add column if not exists visibility text not null default 'class';
alter table public.notes add column if not exists archived boolean not null default false;

create table if not exists public.favorites (
  user_id bigint not null references public.users(id) on delete cascade,
  note_id bigint not null references public.notes(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(user_id, note_id)
);
create table if not exists public.reminders (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  note_id bigint references public.notes(id) on delete cascade,
  title text not null, remind_at timestamptz not null,
  completed boolean not null default false, created_at timestamptz not null default now()
);
create table if not exists public.note_versions (
  id bigint generated by default as identity primary key,
  note_id bigint not null references public.notes(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  title text not null, description text, category text, tags text,
  created_at timestamptz not null default now()
);
create table if not exists public.note_shares (
  note_id bigint not null references public.notes(id) on delete cascade,
  shared_by bigint not null references public.users(id) on delete cascade,
  shared_with text not null, permission text not null default 'view',
  created_at timestamptz not null default now(),
  primary key(note_id, shared_with)
);
create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  user_id bigint references public.users(id) on delete set null,
  action text not null, note_id bigint references public.notes(id) on delete set null,
  metadata jsonb, created_at timestamptz not null default now()
);
create table if not exists public.backups (
  id bigint generated by default as identity primary key,
  created_by bigint references public.users(id) on delete set null,
  label text not null, file_count integer not null default 0,
  size_bytes bigint not null default 0, created_at timestamptz not null default now()
);

create table if not exists public.otp_codes (
  id bigint generated by default as identity primary key,
  email text not null,
  code_hash text not null,
  purpose text not null,
  expires_at bigint not null,
  attempts integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists idx_notes_subject on public.notes(subject);
create index if not exists idx_notes_semester on public.notes(semester);
create index if not exists idx_notes_user on public.notes(user_id);
create index if not exists idx_subjects_semester on public.subjects(semester);

